// 2026-11-05 14:20 +03: generate KwtSMS.VERSION from `version` above, so the User-Agent always carries the
// build's real version and is never a hand-typed constant (#939).
val generateVersionSource by tasks.registering {
    val outDir = layout.buildDirectory.dir("generated/kwtsms-version")
    val libVersion = project.version.toString()
    inputs.property("version", libVersion)
    outputs.dir(outDir)
    doLast {
        val file = outDir.get().file("com/kwtsms/LibraryVersion.kt").asFile
        file.parentFile.mkdirs()
        file.writeText("package com.kwtsms\n\n// Generated by build.gradle.kts, do not edit.\ninternal const val LIBRARY_VERSION = \"$libVersion\"\n")
    }
}
kotlin.sourceSets["main"].kotlin.srcDir(generateVersionSource)

